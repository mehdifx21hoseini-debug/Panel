# Generates FoodLibrary.kt (the built-in food bank) from USDA FoodData Central SR Legacy and the
# curated list in tools/food-bank.json (which foods, their Persian names, categories and portions).
# Every number comes from the USDA file; the script refuses foods or portions it cannot find there.
#
# Usage (from fitos-android/):
#   1. Download https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2021-10-28.zip
#      (public domain, CC0) and unzip it.
#   2. python3 tools/generate_foods.py <FoodData_Central_sr_legacy_food_json_2021-10-28.json> tools/food-bank.json \
#        core/domain/src/main/kotlin/app/fitos/core/domain/nutrition/FoodLibrary.kt
import json
import sys

NUTRIENTS = {"208": "kcal", "203": "protein", "205": "carbs", "204": "fat", "291": "fiber", "269": "sugar", "307": "sodium"}
CATEGORIES = {
    "grains": "GRAINS", "legumes": "LEGUMES", "meat": "MEAT", "poultry": "POULTRY", "seafood": "SEAFOOD", "eggs": "EGGS",
    "dairy": "DAIRY", "vegetables": "VEGETABLES", "fruits": "FRUITS", "nuts_dried": "NUTS_DRIED", "fats": "FATS",
    "sweets": "SWEETS", "drinks": "DRINKS", "condiments": "CONDIMENTS", "supplements": "SUPPLEMENTS",
}
STATES = {"raw": "RAW", "cooked": "COOKED", "na": "NOT_APPLICABLE"}


def kotlin_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def number(v):
    if v is None:
        return "null"
    return repr(float(v))


def main(usda_path, bank_path, out_path):
    usda = {f["fdcId"]: f for f in json.load(open(usda_path, encoding="utf-8"))["SRLegacyFoods"]}
    bank = json.load(open(bank_path, encoding="utf-8"))["foods"]
    keys, ids, lines = set(), set(), []
    for item in bank:
        key, fdc = item["key"], item["fdcId"]
        if key in keys or fdc in ids:
            sys.exit(f"duplicate key or fdcId: {key} {fdc}")
        keys.add(key)
        ids.add(fdc)
        food = usda.get(fdc) or sys.exit(f"fdcId {fdc} ({key}) is not in the USDA file")
        n = {}
        for x in food["foodNutrients"]:
            name = NUTRIENTS.get(x["nutrient"].get("number"))
            if name and "amount" in x:
                n[name] = x["amount"]
        for required in ("kcal", "protein", "carbs", "fat"):
            if required not in n:
                sys.exit(f"{key}: USDA has no {required}")
        usda_grams = [p.get("gramWeight") for p in food.get("foodPortions", [])]
        portions = []
        for p in item.get("portions", []):
            if not any(g is not None and abs(g - p["grams"]) < 0.01 for g in usda_grams):
                sys.exit(f"{key}: portion {p} is not a USDA portion of FDC {fdc}")
            portions.append(f"p({kotlin_string(p['labelFa'])}, {number(p['grams'])})")
        args = [
            kotlin_string(key), str(fdc), kotlin_string(item["nameFa"]), kotlin_string(item["nameEn"]),
            CATEGORIES[item["category"]], STATES[item["state"]],
            number(n["kcal"]), number(n["protein"]), number(n["carbs"]), number(n["fat"]),
            number(n.get("fiber")), number(n.get("sugar")), number(n.get("sodium")),
        ] + portions
        lines.append("        f(" + ", ".join(args) + "),")

    out = [
        "// Generated by tools/generate_foods.py from USDA FoodData Central SR Legacy (public domain, CC0)",
        "// and tools/food-bank.json. Edit those, not this file.",
        "package app.fitos.core.domain.nutrition",
        "",
        "import app.fitos.core.domain.nutrition.FoodCategory.*",
        "import app.fitos.core.domain.nutrition.FoodState.COOKED",
        "import app.fitos.core.domain.nutrition.FoodState.NOT_APPLICABLE",
        "import app.fitos.core.domain.nutrition.FoodState.RAW",
        "",
        "/** The built-in food bank: values per 100 g exactly as USDA publishes them (nutrient numbers 208, 203, 205, 204, 291, 269, 307). */",
        "object FoodLibrary {",
        "    const val VERSION = 1",
        '    const val SOURCE = "USDA FoodData Central, SR Legacy (April 2018)"',
        "",
        "    val byKey: Map<String, LibraryFood> by lazy { all.associateBy { it.key } }",
        "",
        "    val all: List<LibraryFood> = listOf(",
        *lines,
        "    )",
        "",
        "    private fun f(",
        "        key: String, fdcId: Int, nameFa: String, nameEn: String, category: FoodCategory, state: FoodState,",
        "        kcal: Double, protein: Double, carbs: Double, fat: Double, fiber: Double?, sugar: Double?, sodium: Double?,",
        "        vararg portions: FoodPortion,",
        "    ) = LibraryFood(key, fdcId, nameFa, nameEn, category, state, kcal, protein, carbs, fat, fiber, sugar, sodium, portions.toList())",
        "",
        "    private fun p(label: String, grams: Double) = FoodPortion(label, grams)",
        "}",
    ]
    open(out_path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(len(lines), "foods")


if __name__ == "__main__":
    main(*sys.argv[1:4])
